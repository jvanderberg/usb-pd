#!/usr/bin/env python3
"""Project footprints that JLC does not supply (hand-soldered parts). Writes hardware/usbpd.pretty/ and registers it.

OLED_0.69in_96x16_FPC14: solder pads for the 14-way folding FPC of a 0.69" 96x16 COG OLED
(Wisevision N069-9616TSWPG02-H14 drawing, docs/datasheets/N069-9616TSWPG02-H14.pdf p.5):
  contact pitch 0.62 mm, 14 contacts (P0.62 x 13 = 8.06 mm), contact width 0.32 mm, contact length ~2 mm,
  FPC 9 mm wide, 10.49 mm from the panel edge to the contact end; panel 26.3 x 8.0 x 1.2 mm.
Pads are 0.38 x 2.6 mm (longer than the contact so an iron can reach), pin 1 at -x. The FPC is soldered flat
first, then folded 180 deg so the panel lies on the board over the pads (double-sided tape). The F.Fab outline
shows where the folded panel lands (fold allowance ~1.5 mm, approximate: check the real part before the case).
"""
import os
import kskills  # noqa: F401  (puts kicad-skills on sys.path, checks the pin)
from kicad_sexpr import Node, LibTable, load
from kicad_sexpr.board import new_footprint, fp_line, fp_rect
from kicad_sexpr.sexp import Sym, dumps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HW = os.path.join(ROOT, 'hardware')
LIB = os.path.join(HW, 'usbpd.pretty')

PITCH, N, PW, PL = 0.62, 14, 0.38, 2.6
FPC_LEN = 10.49        # panel edge -> contact end
PANEL_L, PANEL_W = 26.3, 8.0
FOLD = 1.5             # length taken by the 180 deg bend (approximate)


def pad(num, x, y, w, h):
    return Node('pad', str(num), Sym('smd'), Sym('rect'), Node('at', round(x, 4), round(y, 4)),
                Node('size', w, h), Node('layers', 'F.Cu', 'F.Mask', 'F.Paste'))


def oled():
    name = 'OLED_0.69in_96x16_FPC14'
    items = []
    x0 = -(N - 1) * PITCH / 2
    for i in range(N):
        items.append(pad(i + 1, x0 + i * PITCH, 0, PW, PL))
    # contact end at y = -1.3 (pad top). FPC runs toward +y, bends, panel comes back over the pads toward -y.
    # simple model: the FPC (plus bend allowance) folds in half -> the panel edge sits at the bend line
    yb = round(-PL / 2 + (FPC_LEN + FOLD) / 2, 3)
    edge = yb
    items.append(fp_rect((-PANEL_W / 2, edge - PANEL_L), (PANEL_W / 2, edge), 'F.Fab', 0.1))
    items.append(fp_line((-4.5, -PL / 2), (-4.5, yb), 'F.Fab', 0.1))
    items.append(fp_line((4.5, -PL / 2), (4.5, yb), 'F.Fab', 0.1))
    # silk: pin-1 mark and the panel outline corners (glass area)
    items.append(fp_line((x0 - 0.6, -PL / 2 - 0.4), (x0 - 0.6, PL / 2 + 0.4), 'F.SilkS', 0.12))
    for sx in (-1, 1):
        items.append(fp_line((sx * (PANEL_W / 2 + 0.2), edge), (sx * (PANEL_W / 2 + 0.2), edge - PANEL_L), 'F.SilkS', 0.12))
    items.append(fp_rect((-PANEL_W / 2 - 0.4, edge - PANEL_L - 0.25), (PANEL_W / 2 + 0.4, max(edge, PL / 2) + 0.25),
                         'F.CrtYd', 0.05))
    fp = new_footprint(name, descr='0.69in 96x16 OLED (SSD1306/SSD1315), 14-pin 0.62 mm folding FPC, hand-soldered',
                       tags='OLED FPC 0.62', attr=('smd', 'exclude_from_bom', 'exclude_from_pos_files'), items=items)
    # the folded panel, FPC and a lit sample frame: generated by tools/oled_3d.py in this footprint's frame
    fp.append(Node('model', '${KIPRJMOD}/usbpd.3dshapes/OLED_0.69in_96x16.wrl',
                   Node('offset', Node('xyz', 0, 0, 0)), Node('scale', Node('xyz', 1, 1, 1)),
                   Node('rotate', Node('xyz', 0, 0, 0))))
    return name, fp


def _at(parent, child):
    return next(i for i, c in enumerate(parent) if c is child)


def ch552p_epvia():
    """JLC's CH552P footprint (JLCImport:CH552P, kept as JLC places it: same origin, rotation, pad numbers) with one
    plated hole in the exposed pad and paste windows that clear it. The EP is the CH552P's only GND and every side of
    it faces a pin row, so its ground has to leave through the pad (board_lint VIA IN PAD / PASTE ON HOLE)."""
    name = 'CH552P_EPVIA'
    fp = load(os.path.join(HW, 'JLCImport.pretty', 'CH552P.kicad_mod'))
    fp[1] = name
    eps = [p for p in fp.find_all('pad') if p.args[0] == '17']
    assert len(eps) == 1, 'CH552P: expected one EP pad'
    eps[0].set('layers', 'F.Cu', 'F.Mask')                      # paste comes from the windows below
    # 0.55 mm windows in the four quadrants, inner edges 0.2 mm from the hole centre (0.13 mm past a 0.3 mm drill);
    # the lower-left one is cut short where the EP has its pin-1 chamfer. Coverage ~40 % of the 2.83 mm^2 EP.
    wins = [(0.475, -0.475, 0.55, 0.55), (-0.475, -0.475, 0.55, 0.55), (0.475, 0.475, 0.55, 0.55),
            (-0.45, 0.4, 0.5, 0.4)]
    last = eps[0]
    for x, y, w, h in wins:
        node = Node('pad', '', Sym('smd'), Sym('rect'), Node('at', x, y), Node('size', w, h), Node('layers', 'F.Paste'))
        fp.insert(_at(fp, last) + 1, node)
        last = node
    hole = Node('pad', '17', Sym('thru_hole'), Sym('circle'), Node('at', 0, 0), Node('size', 0.6, 0.6),
                Node('drill', 0.3), Node('layers', '*.Cu'))
    fp.insert(_at(fp, last) + 1, hole)
    fp.set('descr', 'CH552P (JLC C968536 footprint) with a 0.3 mm GND via in the exposed pad and paste windows clear of it')
    return name, fp


def rlm12_land():
    """NoOutline:RLM12FTCMR005 (strip_outline.py copy of JLC's footprint) with the datasheet land pattern
    (RLM12 DS s6, 2-50 mOhm: pad length b 1.7, width a 1.8, gap L 1.6 -> centres +-1.65). JLC's pads are 1.21 long.
    Footprint origin unchanged (JLC places the body there)."""
    p = os.path.join(HW, 'NoOutline.pretty', 'RLM12FTCMR005.kicad_mod')
    fp = load(p)
    pads = {q.args[0]: q for q in fp.find_all('pad')}
    assert sorted(pads) == ['1', '2'], pads.keys()
    # pad 1 keeps the datasheet inner edge (-0.8) but is 1.0 long: on this board it faces Q1's drain pads (same net,
    # joined by the VOUT_SW pour) with the board edge behind pad 2, so a full-length pad 1 would overlap Q1's pads
    for num, x, length in (('1', -1.3, 1.0), ('2', 1.65, 1.7)):
        pads[num].set('at', x, 0)
        pads[num].set('size', length, 1.8)
    open(p, 'w').write(dumps(fp))
    print('wrote', p, '(datasheet land)')


def main():
    os.makedirs(LIB, exist_ok=True)
    for name, fp in (oled(), ch552p_epvia()):
        p = os.path.join(LIB, name + '.kicad_mod')
        text = dumps(fp)
        open(p, 'w').write(text)
        print('wrote', p)
    rlm12_land()
    t = LibTable.for_project(HW, 'fp')
    if t.add('usbpd', LIB, descr='usbpd project footprints'):
        t.save()
        print('registered usbpd in', t.path)


if __name__ == '__main__':
    main()
