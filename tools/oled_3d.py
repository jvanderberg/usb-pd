#!/usr/bin/env python3
"""3D model of the folded 0.69" 96x16 OLED for the usbpd:OLED_0.69in_96x16_FPC14 footprint, as VRML 2.0
(hardware/usbpd.3dshapes/OLED_0.69in_96x16.wrl). Dimensions from the Wisevision N069-9616TSWPG02-H14 outline drawing
(docs/datasheets/N069-9616TSWPG02-H14.pdf, s1.4):
  panel (base glass) 26.3 x 8.0, cap glass 22.7 long, polarizer 21.7 x 7.0 x 0.2 starting 0.5 from the far end,
  viewing area 19.26 x 5.18 at 1.27 / 0.8, active area 17.26 x 3.18 at 2.27 / 1.8 (from the far end / the pin-14
  edge), total 1.2 thick; FPC 9 wide, 10.49 from the panel edge to the contact end.
Footprint frame (footprints.py): pads along x at y = 0 (pin 1 at -x, contact end at y = -1.3), the FPC runs to +y,
folds 180 deg, and the panel lies face up over the pads with its FPC end at y = EDGE and its far end at EDGE - 26.3.
The active area shows a real frame from the firmware (firmware/test/screens.c, frame "pps-on"), lit white.
Glass, FPC and tape thicknesses are approximate (drawing gives only the 1.2 mm total).
VRML units here are KiCad's: 0.1 inch (2.54 mm)."""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'hardware', 'usbpd.3dshapes', 'OLED_0.69in_96x16.wrl')
FW = os.path.join(ROOT, 'firmware')
sys.path.insert(0, os.path.join(ROOT, 'tools'))

PL = 2.6                          # pad length (footprints.py)
FPC_LEN, FOLD = 10.49, 1.5
EDGE = round(-PL / 2 + (FPC_LEN + FOLD) / 2, 3)   # panel FPC-end edge, as footprints.py draws it
FAR = EDGE - 26.3                 # panel far end
HW_ = 4.0                         # half panel width
Z0 = 0.30                         # panel underside: soldered FPC (0.1) + double-sided tape (~0.2)
G1 = Z0 + 0.45                    # base glass top
G2 = G1 + 0.50                    # cap glass top
POL = G2 + 0.20                   # polarizer top (Z0 + 1.15 ~ the drawing's 1.2 incl. tolerances)

# x across the panel: the drawing's pin-14 edge is +x on this footprint (pin 1 at -x)
VA_X = (HW_ - 0.8 - 5.18, HW_ - 0.8)
AA_X = (HW_ - 1.8 - 3.18, HW_ - 1.8)
AA_Y0 = FAR + 2.27                # active area starts 2.27 from the far end
COL_P, ROW_P, COL_W, ROW_H = 0.18, 0.20, 0.16, 0.18


def frame(name='pps-on'):
    subprocess.run(['make', '-s', '-C', FW, 'build/screens'], check=True, stdout=subprocess.DEVNULL)
    lines = subprocess.run([os.path.join(FW, 'build', 'screens')], check=True, capture_output=True,
                           text=True).stdout.splitlines()
    for i in range(0, len(lines), 3):
        if lines[i].split('|')[0] == name:
            return [bytes.fromhex(lines[i + 1]), bytes.fromhex(lines[i + 2])]
    raise SystemExit('no frame %r from firmware/build/screens' % name)


class Wrl:
    def __init__(self):
        self.parts = []

    def mat(self, rgb, shin=0.2, spec=0.1, emis=(0, 0, 0), transp=0.0):
        return ('material Material { diffuseColor %.3f %.3f %.3f emissiveColor %.3f %.3f %.3f specularColor %.3f %.3f %.3f'
                ' ambientIntensity 0.3 shininess %.2f transparency %.2f }' % (*rgb, *emis, spec, spec, spec, shin, transp))

    def boxes(self, boxes, mat):
        """boxes: (x0, x1, y0, y1, z0, z1) in footprint mm (y down); one Shape per material"""
        pts, idx = [], []
        for x0, x1, y0, y1, z0, z1 in boxes:
            b = len(pts)
            for z in (z0, z1):
                for x, y in ((x0, y0), (x1, y0), (x1, y1), (x0, y1)):
                    pts.append((x / 2.54, -y / 2.54, z / 2.54))
            for f in ((0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)):
                idx.append(' '.join(str(b + i) for i in f) + ' -1')
        self.parts.append('Shape {\n  appearance Appearance { %s }\n  geometry IndexedFaceSet {\n    solid FALSE\n'
                          '    coord Coordinate { point [\n%s\n    ] }\n    coordIndex [\n%s\n    ]\n  }\n}\n'
                          % (mat, ',\n'.join('      %.5f %.5f %.5f' % p for p in pts),
                             ',\n'.join('      ' + i for i in idx)))

    def text(self):
        return '#VRML V2.0 utf8\n# generated by tools/oled_3d.py\n' + ''.join(self.parts)


def main():
    pages = frame()
    w = Wrl()
    amber = w.mat((0.80, 0.50, 0.12), shin=0.4, spec=0.3)
    # FPC: flat over the pads (contacts down), the 180 deg bend, and the bonded end on the base-glass ledge
    w.boxes([(-4.5, 4.5, -PL / 2, EDGE, 0.0, 0.10),
             (-4.5, 4.5, EDGE, EDGE + 0.35, 0.0, G1 + 0.08),
             (-4.5, 4.5, EDGE - 0.9, EDGE + 0.35, G1, G1 + 0.08)], amber)
    w.boxes([(-HW_, HW_, FAR, EDGE, Z0, G1)], w.mat((0.55, 0.62, 0.60), shin=0.8, spec=0.6, transp=0.35))   # base glass
    w.boxes([(-HW_, HW_, FAR, FAR + 22.7, G1, G2)], w.mat((0.45, 0.50, 0.50), shin=0.8, spec=0.6, transp=0.4))  # cap
    w.boxes([(-3.05, 3.05, FAR + 22.95, FAR + 23.75, G1, G1 + 0.25)], w.mat((0.10, 0.10, 0.12), spec=0.4))   # COG IC
    w.boxes([(-3.5, 3.5, FAR + 0.5, FAR + 22.2, G2, POL)], w.mat((0.03, 0.03, 0.04), shin=0.6, spec=0.25))  # polarizer
    w.boxes([(VA_X[0], VA_X[1], FAR + 1.27, FAR + 20.53, POL, POL + 0.004)],
            w.mat((0.015, 0.015, 0.02), shin=0.9, spec=0.5))                                              # viewing area
    # lit pixels: column c runs along -y from the FPC end (so the text reads left to right with the board's USB-C
    # at the left), row r across x from the -x edge
    px = []
    for page in range(2):
        for c in range(96):
            for bit in range(8):
                if (pages[page][c] >> bit) & 1:
                    r = page * 8 + bit
                    ya = AA_Y0 + 17.26 - c * COL_P
                    xa = AA_X[0] + r * ROW_P
                    px.append((xa, xa + ROW_H, ya - COL_W, ya, POL + 0.004, POL + 0.012))
    w.boxes(px, w.mat((0.9, 0.93, 1.0), emis=(0.95, 0.97, 1.0), spec=0.0))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write(w.text())
    print('wrote', OUT, '(%d lit pixels)' % len(px))


if __name__ == '__main__':
    main()
