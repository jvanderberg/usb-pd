#!/usr/bin/env python3
"""Generate src/ntc_table.h: CH552 ADC counts vs temperature for the board's NTC divider.

Divider (schematic): R11 2.2k from VCC (+5V, the ADC reference) to P3.2/AIN3, RT1 NTC to GND.
CH552 ADC: 8 bit, result = Vin / VCC x 255 (CH552 DS s15.3). Ratiometric: VCC cancels.
NTC: Murata NCP15XH103F03RC, R25 = 10k 1 %, B25/50 = 3380 K (datasheet, B-constant code XH).
"""
import math
import os

R25, B, T25 = 10000.0, 3380.0, 298.15
R_TOP = 2200.0
T_MIN, T_MAX, STEP = -20, 125, 5


def counts(t_c):
    r = R25 * math.exp(B * (1.0 / (t_c + 273.15) - 1.0 / T25))
    return round(255.0 * r / (r + R_TOP))


def main():
    temps = list(range(T_MIN, T_MAX + 1, STEP))
    vals = [counts(t) for t in temps]
    assert all(a > b for a, b in zip(vals, vals[1:])), 'table must fall strictly with temperature'
    out = os.path.join(os.path.dirname(__file__), '..', 'src', 'ntc_table.h')
    lines = [
        '/* generated by tools/gen_ntc_table.py - do not edit */',
        '#ifndef NTC_TABLE_H', '#define NTC_TABLE_H',
        '#define NTC_T_MIN_C %d' % T_MIN, '#define NTC_T_STEP_C %d' % STEP, '#define NTC_N %d' % len(vals),
        '/* ADC counts at NTC_T_MIN_C + i * NTC_T_STEP_C (R_top %.0f ohm to VCC, NTC %.0f ohm B%.0f) */' % (R_TOP, R25, B),
        'static const NTC_CODE uint8_t ntc_counts[NTC_N] = {',
        '    ' + ', '.join(str(v) for v in vals),
        '};', '#endif', '']
    open(out, 'w').write('\n'.join(lines))
    print('wrote', os.path.normpath(out), list(zip(temps, vals))[::4])


if __name__ == '__main__':
    main()
